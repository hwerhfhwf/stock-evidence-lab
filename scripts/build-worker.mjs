import { readFile, writeFile, mkdir, copyFile, rm } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const normalizeLineEndings = content => content.replace(/\r\n?/g, '\n');

const [html, css, app, diagnosisModel, finscopeData] = (await Promise.all([
  readFile(resolve(root, 'ui/index.html'), 'utf8'),
  readFile(resolve(root, 'ui/styles.css'), 'utf8'),
  readFile(resolve(root, 'ui/app.js'), 'utf8'),
  readFile(resolve(root, 'ui/diagnosis-model.js'), 'utf8'),
  readFile(resolve(root, 'ui/finscope-data.js'), 'utf8'),
])).map(normalizeLineEndings);
const uiModule = `// Generated by scripts/build-worker.mjs. Do not edit.\nexport const page = ${JSON.stringify(html)};\nexport const styles = ${JSON.stringify(css)};\nexport const appScript = ${JSON.stringify(app)};\nexport const diagnosisModelScript = ${JSON.stringify(diagnosisModel)};\nexport const finscopeDataScript = ${JSON.stringify(finscopeData)};\n`;
await writeFile(resolve(root, 'worker/ui.js'), uiModule, 'utf8');
await mkdir(resolve(root, 'dist/server'), { recursive: true });
await mkdir(resolve(root, 'dist/.openai'), { recursive: true });
await Promise.all(['app.mjs','data.mjs','engine.mjs','health-model.js'].map(name=>rm(resolve(root,'dist',name),{force:true})));
await Promise.all([
  copyFile(resolve(root, 'ui/index.html'), resolve(root, 'dist/index.html')),
  copyFile(resolve(root, 'ui/styles.css'), resolve(root, 'dist/styles.css')),
  copyFile(resolve(root, 'ui/app.js'), resolve(root, 'dist/app.js')),
  copyFile(resolve(root, 'ui/diagnosis-model.js'), resolve(root, 'dist/diagnosis-model.js')),
  copyFile(resolve(root, 'ui/finscope-data.js'), resolve(root, 'dist/finscope-data.js')),
  copyFile(resolve(root, 'worker/index.js'), resolve(root, 'dist/server/index.js')),
  copyFile(resolve(root, 'worker/fuyao.js'), resolve(root, 'dist/server/fuyao.js')),
  copyFile(resolve(root, 'worker/research.js'), resolve(root, 'dist/server/research.js')),
  copyFile(resolve(root, 'worker/ui.js'), resolve(root, 'dist/server/ui.js')),
  copyFile(resolve(root, '.openai/hosting.json'), resolve(root, 'dist/.openai/hosting.json')),
]);
console.log('built one multidimensional diagnosis UI for dist and Worker');
